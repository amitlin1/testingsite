// Build the air-gap application-schema SQL for the DB server.
//
//   node scripts/build-airgap-schema.js
//
// Writes prod-deploy/db-server/init/02-app-schema.sql, which the postgres image
// applies automatically on a FRESH data volume (files in
// /docker-entrypoint-initdb.d run in filename order, against POSTGRES_DB).
//
// WHY NOT `prisma migrate deploy`: the shipped app image is a Next.js standalone
// build — it contains neither the Prisma CLI nor the migrations folder, and the
// production network has no npm registry. Plain SQL applied by postgres itself
// needs no tooling at all on the target machine.
//
// The file contains two parts:
//   1. every prisma/migrations/*/migration.sql, concatenated in order
//   2. the _prisma_migrations bookkeeping rows that mark them all as applied
//
// Part 2 matters: without it a later `prisma migrate deploy` from a connected
// machine would try to re-run migration 0_init against a populated database and
// fail. The checksum is a plain sha256 of the migration.sql bytes — verified
// against the checksums Prisma itself recorded.

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const CRLF = String.fromCharCode(13, 10);
const LF = String.fromCharCode(10);

const repoRoot = path.join(__dirname, "..");
const migrationsDir = path.join(repoRoot, "prisma", "migrations");
const outPath = path.join(
  repoRoot,
  "prod-deploy",
  "db-server",
  "init",
  "02-app-schema.sql",
);

const migrations = fs
  .readdirSync(migrationsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  // Timestamp-prefixed names sort chronologically; "0_init" sorts first, which
  // is exactly the order Prisma applied them in.
  .sort();

if (migrations.length === 0) {
  console.error("No migrations found in", migrationsDir);
  process.exit(1);
}

const parts = [];

parts.push(`-- ===========================================================================
-- APPLICATION SCHEMA — generated, do not edit by hand
-- ===========================================================================
-- Generated by scripts/build-airgap-schema.js from prisma/migrations/.
-- Applied automatically by the postgres container on a FRESH data volume.
--
-- To apply it to an EXISTING database instead, run this whole file in DBeaver
-- against the application database. It is NOT idempotent — run it once, on an
-- empty database.
--
-- Migrations included (${migrations.length}):
${migrations.map((m) => `--   ${m}`).join("\n")}
-- ===========================================================================

`);

for (const name of migrations) {
  const sqlPath = path.join(migrationsDir, name, "migration.sql");
  if (!fs.existsSync(sqlPath)) {
    console.warn(`  ! ${name} has no migration.sql — skipped`);
    continue;
  }
  const sql = fs.readFileSync(sqlPath, "utf8");
  parts.push(`
-- ---------------------------------------------------------------------------
-- migration: ${name}
-- ---------------------------------------------------------------------------
${sql}
`);
}

// ---- Prisma bookkeeping ---------------------------------------------------
parts.push(`
-- ===========================================================================
-- Prisma migration bookkeeping
-- ===========================================================================
-- Marks every migration above as already applied, so a future
-- \`prisma migrate deploy\` run from a connected machine applies only NEW ones
-- instead of trying to re-create existing tables.
-- Guarded with NOT EXISTS, so re-running this section is harmless.

CREATE TABLE IF NOT EXISTS public._prisma_migrations (
    id                  VARCHAR(36)  PRIMARY KEY,
    checksum            VARCHAR(64)  NOT NULL,
    finished_at         TIMESTAMPTZ,
    migration_name      VARCHAR(255) NOT NULL,
    logs                TEXT,
    rolled_back_at      TIMESTAMPTZ,
    started_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    applied_steps_count INTEGER      NOT NULL DEFAULT 0
);
`);

for (const name of migrations) {
  const sqlPath = path.join(migrationsDir, name, "migration.sql");
  if (!fs.existsSync(sqlPath)) continue;
  // sha256 of the LF form, not of the bytes on disk. core.autocrlf checks
  // these out with CRLF on Windows, while prisma computes the checksum from
  // the LF file inside the Linux container. Hashing the raw bytes here writes
  // a checksum that can never match there, and the next `prisma migrate
  // deploy` refuses to run -- "migration modified after being applied".
  const checksum = crypto
    .createHash("sha256")
    .update(fs.readFileSync(sqlPath, "utf8").split(CRLF).join(LF), "utf8")
    .digest("hex");
  parts.push(`
INSERT INTO public._prisma_migrations
       (id, checksum, finished_at, migration_name, started_at, applied_steps_count)
SELECT gen_random_uuid()::text, '${checksum}', now(), '${name}', now(), 1
WHERE NOT EXISTS (SELECT 1 FROM public._prisma_migrations WHERE migration_name = '${name}');`);
}

parts.push("\n");

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, parts.join(""), "utf8");

console.log(`wrote ${outPath}`);
console.log(`  ${migrations.length} migrations, ${(fs.statSync(outPath).size / 1024).toFixed(0)} KB`);
